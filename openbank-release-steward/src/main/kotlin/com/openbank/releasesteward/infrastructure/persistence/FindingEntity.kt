package com.openbank.releasesteward.infrastructure.persistence

import com.openbank.releasesteward.domain.model.FindingSeverity
import com.openbank.releasesteward.domain.model.FindingStatus
import com.openbank.releasesteward.domain.model.ReleaseInvariantCheckType
import io.quarkus.hibernate.reactive.panache.kotlin.PanacheCompanionBase
import io.quarkus.hibernate.reactive.panache.kotlin.PanacheEntityBase
import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.EnumType
import jakarta.persistence.Enumerated
import jakarta.persistence.Id
import jakarta.persistence.Table
import java.math.BigDecimal
import java.time.Instant
import java.util.UUID

/**
 * Persisted release-steward finding (ADR-0165). Reactive Panache entity (the fleet standard). The id
 * is assigned in the domain (Ids.newId()), not generated by the DB.
 */
@Entity
@Table(name = "findings")
class FindingEntity : PanacheEntityBase {

    companion object : PanacheCompanionBase<FindingEntity, UUID>

    @Id
    @Column(columnDefinition = "uuid")
    lateinit var id: UUID

    @Column(name = "check_type", nullable = false)
    @Enumerated(EnumType.STRING)
    lateinit var checkType: ReleaseInvariantCheckType

    @Column(name = "severity", nullable = false)
    @Enumerated(EnumType.STRING)
    lateinit var severity: FindingSeverity

    @Column(name = "detected_at", nullable = false)
    lateinit var detectedAt: Instant

    @Column(name = "title", columnDefinition = "TEXT", nullable = false)
    lateinit var title: String

    @Column(name = "component", nullable = false)
    lateinit var component: String

    // Only the openapi-collision check (ADR-0165 check 4) is PR-scoped; checks 1-3 read the repo
    // checkout directly and have no PR to point at.
    @Column(name = "pr_number")
    var prNumber: Int? = null

    @Column(name = "pr_url")
    var prUrl: String? = null

    @Column(name = "raw_metric_value", nullable = false)
    lateinit var rawMetricValue: BigDecimal

    @Column(name = "threshold", nullable = false)
    lateinit var threshold: BigDecimal

    @Column(name = "root_cause", columnDefinition = "TEXT")
    var rootCause: String? = null

    @Column(name = "proposal_url")
    var proposalUrl: String? = null

    @Column(name = "proposed_fix_diff", columnDefinition = "TEXT")
    var proposedFixDiff: String? = null

    @Column(name = "status", nullable = false)
    @Enumerated(EnumType.STRING)
    lateinit var status: FindingStatus

    @Column(name = "diagnosed_at")
    var diagnosedAt: Instant? = null

    @Column(name = "proposed_at")
    var proposedAt: Instant? = null
}
