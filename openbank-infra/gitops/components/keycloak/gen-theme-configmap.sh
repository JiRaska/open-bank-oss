#!/usr/bin/env bash
# Generates both login-theme ConfigMaps from ./theme and the Admin UI brand asset.
#
# ArgoCD applies YAML files. keycloak.yaml maps flat ConfigMap keys back to the
# theme paths. Re-run this script and commit the output after a source change.
set -euo pipefail
cd "$(dirname "$0")"

write_theme() {
  local name="$1" image="$2" source="theme/$1/login" file
  shift 2
  local configmap="keycloak-theme-$name" output="keycloak-theme-$name.yaml"

  {
    echo "# GENERATED by gen-theme-configmap.sh — do not hand-edit. Source: ./$source"
    echo "apiVersion: v1"
    echo "kind: ConfigMap"
    echo "metadata:"
    echo "  name: $configmap"
    echo "  namespace: iam"
    echo "  labels:"
    echo "    app.kubernetes.io/name: keycloak"
    echo "    app.kubernetes.io/part-of: iam"
    echo "data:"
    for file in theme.properties "$@"; do
      echo "  ${file##*/}: |"
      sed 's/^/    /; s/[[:space:]]*$//' "$source/$file"
    done
    echo "binaryData:"
    echo "  ${image##*/}: $(base64 < "$image" | tr -d '\n')"
  } > "$output"
  echo "wrote $output ($(wc -c < "$output") bytes)"
}

write_theme openbank theme/openbank/login/resources/img/openbank-vault.png \
  resources/css/openbank.css messages/messages_en.properties
write_theme openbank-admin ../../../../openbank-admin-ui/public/brand/explorer-prague-lion.webp \
  resources/css/openbank-admin.css messages/messages_en.properties messages/messages_cs.properties

# Roll the pod after either theme changes so Keycloak drops cached resources.
SUM=$(cat keycloak-theme-openbank.yaml keycloak-theme-openbank-admin.yaml | shasum -a 256 | cut -c1-16)
sed -E "s|(openbank\.dev/theme-checksum: )\".*\"|\1\"$SUM\"|" keycloak.yaml > keycloak.yaml.tmp
mv keycloak.yaml.tmp keycloak.yaml
echo "stamped theme-checksum=$SUM into keycloak.yaml"
