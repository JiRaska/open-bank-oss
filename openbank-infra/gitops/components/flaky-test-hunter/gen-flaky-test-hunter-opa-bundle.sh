# Generates the agents-only bundle for flaky-test-hunter's PR-path policy decision point.
# Mirrors agent/gen-opa-bundle-configmap.sh: subPath mounts require a pod checksum rollout.
set -euo pipefail
cd "$(dirname "$0")"

REGO=../../../opa/policies/agents.rego
DATA=../../../../openbank-libs/governance/agents-opa-data.yaml
MANIFEST=../../../opa/bundle.manifest
OUT=flaky-test-hunter-opa-bundle.yaml

CHECKSUM=$(cat "$REGO" "$DATA" "$MANIFEST" | \
  (if command -v sha256sum >/dev/null 2>&1; then sha256sum; else shasum -a 256; fi) | cut -c1-16)

{
  echo "# GENERATED by gen-flaky-test-hunter-opa-bundle.sh — do not hand-edit."
  echo "# Source: opa/policies/agents.rego + openbank-libs/governance/agents-opa-data.yaml + opa/bundle.manifest"
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: flaky-test-hunter-opa-bundle"
  echo "  namespace: flaky-test-hunter"
  echo "  labels:"
  echo "    app.kubernetes.io/name: flaky-test-hunter"
  echo "    app.kubernetes.io/part-of: flaky-test-hunter"
  echo "  annotations:"
  echo "    openbank.tech/policy-checksum: \"$CHECKSUM\""
  echo "data:"
  echo "  agents.rego: |"
  sed 's/^/    /' "$REGO" | sed 's/[[:space:]]*$//'
  echo "  agents-data.yaml: |"
  sed 's/^/    /' "$DATA" | sed 's/[[:space:]]*$//'
  echo "  manifest.json: |"
  sed 's/^/    /' "$MANIFEST" | sed 's/[[:space:]]*$//'
  printf '\n'
} > "$OUT"

echo "wrote $OUT (checksum $CHECKSUM, $(wc -c < "$OUT") bytes)"

DEPLOYMENT=flaky-test-hunter.yaml
if [ -f "$DEPLOYMENT" ]; then
  sed -i.bak "s|openbank.tech/policy-checksum: \"[^\"]*\"|openbank.tech/policy-checksum: \"$CHECKSUM\"|" "$DEPLOYMENT"
  rm -f "${DEPLOYMENT}.bak"
  echo "patched $DEPLOYMENT annotation → $CHECKSUM"
fi
