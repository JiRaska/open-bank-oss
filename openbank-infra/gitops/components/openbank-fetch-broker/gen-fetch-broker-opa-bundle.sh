#!/usr/bin/env bash
# Generates fetch-broker-opa-bundle.yaml (the ConfigMap ArgoCD applies) for openbank-fetch-broker
# (ADR-0387). The broker authorizes every web.fetch through the SHARED ADR-0034 PDP — it queries
# data.openbank.rest.allow for an AI_AGENT on action read.public_web, which rest.rego bridges to
# agents.rego (charter grant + data_scope.public_web.hosts). So this bundle embeds the full shared
# policy set (rest.rego + agents.rego + derived agents/rules data + manifest); no service-local
# REST extension is needed.
#
# A checksum annotation rolls the Deployment when the policy changes (subPath mounts do not
# hot-reload). After editing any embedded source, re-run + commit. Editing the shared sources
# (agents.yaml / rules.yaml / rest.rego / agents.rego) restamps EVERY service's bundle —
# regenerate them all: find openbank-infra/gitops/components -name 'gen-*opa-bundle*.sh' | sort | xargs -n1 bash
set -euo pipefail
REPO="$(git rev-parse --show-toplevel)"

REST_REGO=$REPO/openbank-libs/governance/policies/rest.rego
AGENTS_REGO=$REPO/openbank-infra/opa/policies/agents.rego
AGENTS_YAML=$REPO/openbank-libs/governance/agents-opa-data.yaml
RULES_YAML=$REPO/openbank-libs/governance/rules-opa-data.yaml
MANIFEST=$REPO/openbank-infra/opa/bundle.manifest

# Portable SHA-256: prefer sha256sum (Linux), fall back to shasum -a 256 (macOS).
CHECKSUM=$(printf '%s\n' \
    "$(cat "$REST_REGO")" \
    "$(cat "$AGENTS_REGO")" \
    "$(cat "$AGENTS_YAML")" \
    "$(cat "$RULES_YAML")" \
    "$(cat "$MANIFEST")" | \
  (command -v sha256sum >/dev/null 2>&1 && sha256sum || shasum -a 256) | cut -c1-16)

OUT=$REPO/openbank-infra/gitops/components/openbank-fetch-broker/fetch-broker-opa-bundle.yaml

{
  echo "# GENERATED by gen-fetch-broker-opa-bundle.sh — do not hand-edit."
  echo "# Source: rest.rego + agents.rego + agents-opa-data.yaml + rules-opa-data.yaml + bundle.manifest"
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: fetch-broker-opa-bundle"
  echo "  namespace: fetch-broker"
  echo "  labels:"
  echo "    app.kubernetes.io/name: openbank-fetch-broker"
  echo "    app.kubernetes.io/part-of: fetch-broker"
  echo "  annotations:"
  echo "    openbank.tech/policy-checksum: \"$CHECKSUM\""
  echo "data:"
  echo "  rest.rego: |"
  sed 's/^/    /' "$REST_REGO" | sed 's/[[:space:]]*$//'
  echo "  agents.rego: |"
  sed 's/^/    /' "$AGENTS_REGO" | sed 's/[[:space:]]*$//'
  echo "  agents-data.yaml: |"
  sed 's/^/    /' "$AGENTS_YAML" | sed 's/[[:space:]]*$//'
  echo "  rules-data.yaml: |"
  sed 's/^/    /' "$RULES_YAML" | sed 's/[[:space:]]*$//'
  echo "  manifest.json: |"
  sed 's/^/    /' "$MANIFEST" | sed 's/[[:space:]]*$//'
  printf '\n'
} > "$OUT"

echo "wrote $OUT (checksum $CHECKSUM)"

# Sync the Deployment pod-roll annotation so a policy change always triggers a rollout
# (subPath mounts do NOT hot-reload).
DEPLOYMENT=$REPO/openbank-infra/gitops/components/openbank-fetch-broker/fetch-broker.yaml
if [ -f "$DEPLOYMENT" ]; then
  sed -i.bak "s|openbank.tech/policy-checksum: \"[^\"]*\"|openbank.tech/policy-checksum: \"$CHECKSUM\"|" "$DEPLOYMENT"
  rm -f "${DEPLOYMENT}.bak"
  echo "patched $DEPLOYMENT annotation → $CHECKSUM"
fi
