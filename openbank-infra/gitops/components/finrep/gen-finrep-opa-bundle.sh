#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
set -euo pipefail
REPO="$(git rev-parse --show-toplevel)"

REST_REGO=$REPO/openbank-libs/governance/policies/rest.rego
FINREP_REST_EXT=$REPO/openbank-infra/gitops/components/finrep/finrep_rest_ext.rego
AGENTS_REGO=$REPO/openbank-infra/opa/policies/agents.rego
AGENTS_YAML=$REPO/openbank-libs/governance/agents-opa-data.yaml
RULES_YAML=$REPO/openbank-libs/governance/rules-opa-data.yaml
MANIFEST=$REPO/openbank-infra/opa/bundle.manifest

CHECKSUM=$(printf '%s\n' \
    "$(cat "$REST_REGO")" \
    "$(cat "$FINREP_REST_EXT")" \
    "$(cat "$AGENTS_REGO")" \
    "$(cat "$AGENTS_YAML")" \
    "$(cat "$RULES_YAML")" \
    "$(cat "$MANIFEST")" | \
  (command -v sha256sum >/dev/null 2>&1 && sha256sum || shasum -a 256) | cut -c1-16)

OUT=$REPO/openbank-infra/gitops/components/finrep/finrep-opa-bundle.yaml

{
  echo "# GENERATED by gen-finrep-opa-bundle.sh — do not hand-edit."
  echo "# Source: rest.rego + finrep_rest_ext.rego + agents.rego + agents-opa-data.yaml + rules-opa-data.yaml + bundle.manifest"
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: finrep-opa-bundle"
  echo "  namespace: finrep"
  echo "  labels:"
  echo "    app.kubernetes.io/name: finrep-service"
  echo "    app.kubernetes.io/part-of: finrep"
  echo "  annotations:"
  echo "    openbank.tech/policy-checksum: \"$CHECKSUM\""
  echo "data:"
  echo "  rest.rego: |"
  sed 's/^/    /' "$REST_REGO" | expand -t 4 | sed 's/[[:space:]]*$//'
  echo "  finrep_rest_ext.rego: |"
  sed 's/^/    /' "$FINREP_REST_EXT" | expand -t 4 | sed 's/[[:space:]]*$//'
  echo "  agents.rego: |"
  sed 's/^/    /' "$AGENTS_REGO" | expand -t 4 | sed 's/[[:space:]]*$//'
  echo "  agents-data.yaml: |"
  sed 's/^/    /' "$AGENTS_YAML" | expand -t 4 | sed 's/[[:space:]]*$//'
  echo "  rules-data.yaml: |"
  sed 's/^/    /' "$RULES_YAML" | expand -t 4 | sed 's/[[:space:]]*$//'
  echo "  manifest.json: |"
  sed 's/^/    /' "$MANIFEST" | expand -t 4 | sed 's/[[:space:]]*$//'
  printf '\n'
} > "$OUT"

echo "wrote $OUT (checksum $CHECKSUM)"

# Restart the pod when the mounted subPath policy changes.
WORKLOAD=$REPO/openbank-infra/gitops/components/finrep/finrep-service.yaml
if [ -f "$WORKLOAD" ]; then
  sed -i.bak "s|openbank.tech/policy-checksum: \"[^\"]*\"|openbank.tech/policy-checksum: \"$CHECKSUM\"|" "$WORKLOAD"
  rm -f "${WORKLOAD}.bak"
  echo "patched $WORKLOAD annotation → $CHECKSUM"
fi
