"""Embed .github/scripts/standing-critical-digest.py in the ConfigMap the in-cluster
critical-alert-digest CronJob mounts (#6432).

The script stays the single source of truth: its --self-test runs on every PR
(gate standing-critical-digest-guards), and this generator copies it byte for byte, so the
CronJob can never run a fork of the logic the gate tested. Argo CD renders the component as
a plain directory, so a kustomize configMapGenerator cannot reach a file outside it; a derived
file plus a drift gate is the remaining honest option.

  gen-critical-alert-digest-configmap.py            write the ConfigMap
  gen-critical-alert-digest-configmap.py --check    exit 1 if the committed copy drifted
  gen-critical-alert-digest-configmap.py --self-test
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".github/scripts/standing-critical-digest.py"
TARGET = ROOT / "openbank-infra/gitops/components/observability/configmap-critical-alert-digest.yaml"

HEADER = """# SPDX-License-Identifier: Apache-2.0
# Copyright (c) OpenBank contributors. Licensed under the Apache License, Version 2.0.
#
# DO NOT EDIT -- generated by openbank-infra/scripts/gen-critical-alert-digest-configmap.py
# from .github/scripts/standing-critical-digest.py (gate critical-alert-digest-configmap-drift).
# Mounted by cronjob-critical-alert-digest.yaml.
apiVersion: v1
kind: ConfigMap
metadata:
  name: critical-alert-digest-script
  namespace: observability
  labels:
    app.kubernetes.io/part-of: observability
    app.kubernetes.io/component: critical-alert-digest
data:
  standing-critical-digest.py: |
"""


def render(source: str) -> str:
    body = "".join(("    " + line) if line.strip() else "\n" for line in source.splitlines(keepends=True))
    if not body.endswith("\n"):
        body += "\n"
    return HEADER + body


def self_test() -> None:
    import yaml  # PyYAML is on every CI lane that runs gates

    sample = "#!/usr/bin/env python3\nx = 1\n\n\ndef f():\n    return 'a: b'\n"
    parsed = yaml.safe_load(render(sample))
    assert parsed["data"]["standing-critical-digest.py"] == sample, "embedding must round-trip byte for byte"
    real = SOURCE.read_text(encoding="utf-8")
    assert yaml.safe_load(render(real))["data"]["standing-critical-digest.py"] == real, "the real script must round-trip"
    assert render(sample) != render(sample + "y = 2\n"), "a source edit must change the output"
    print("self-test ok: gen-critical-alert-digest-configmap (round-trip, drift-sensitive)")


def main() -> int:
    if "--self-test" in sys.argv:
        self_test()
        return 0
    expected = render(SOURCE.read_text(encoding="utf-8"))
    if "--check" in sys.argv:
        actual = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if actual != expected:
            print(f"::error::{TARGET.relative_to(ROOT)} drifted from {SOURCE.relative_to(ROOT)} -- "
                  "run python3 openbank-infra/scripts/gen-critical-alert-digest-configmap.py and commit.")
            return 1
        print("critical-alert-digest ConfigMap matches its source: 1 script")
        print("SUBJECTS=1")
        return 0
    TARGET.write_text(expected, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
