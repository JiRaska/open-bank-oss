"""Generate the per-service alert baseline from the deployed-workload inventory.

The inventory is the repo's own scrape contract: every Deployment/Rollout/StatefulSet declaring a
container port named `management` (gitops_facts.management_port_workloads). From it this emits ONE
PrometheusRule, `prometheus-rules-service-inventory.yaml`:

  * a recording rule per (namespace, workload): `openbank:expected_service:info == 1`. It is the
    machine-readable "this workload is supposed to exist" list, and the only thing in the alert set
    that changes when a service is added;
  * three alerts that join against it, so every inventoried service is covered with no per-service
    hand-written rule:
      ExpectedWorkloadAbsent     the inventory names a workload no kube-state/rollout series exists
                                 for -- a Deployment deleted, never synced, or renamed. The fleet
                                 "no available replicas" alerts cannot see this: an absent subject
                                 is an empty result, not a zero.
      ServiceHttp5xxRatioHigh    per-workload 5xx ratio over the pods' own http_server_requests.
      ServiceRestartBurst        container restarts summed per workload, not per pod.
  "No ready pods" is deliberately NOT regenerated here: DeploymentNoAvailableReplicas /
  RolloutNoAvailableReplicas already cover every workload by label, and a second rule over the same
  subject pages twice for one outage.

DERIVED DATA -- never hand-edit. Re-run after adding a service:

    python3 openbank-infra/scripts/gen-service-alert-rules.py

The drift gate `gen-service-alert-rules-drift-gate` re-runs this and fails on any diff.
"""
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from gitops_facts import management_port_workloads  # noqa: E402

OUT_REL = Path("openbank-infra/gitops/components/observability/prometheus-rules-service-inventory.yaml")

# Pod -> owning workload. Deployment and Rollout pods are `<workload>-<rs-hash>-<5 chars>`.
# StatefulSet pods (`<name>-0`) do not match, so the two pod-keyed alerts do not see them; the
# absence alert reads workload objects and does.
POD_TO_WORKLOAD = '"workload", "$1", "pod", "(.+)-[a-z0-9]{6,10}-[a-z0-9]{5}"'

HEADER = """\
# GENERATED by openbank-infra/scripts/gen-service-alert-rules.py -- DO NOT EDIT.
# Per-service alert baseline derived from the deployed-workload inventory (every workload that
# declares a `management` container port). A new service gets these rules by regenerating; the
# `gen-service-alert-rules-drift-gate` gate fails until it has. See the generator for the design.
"""

ABSENT_EXPR = """\
openbank:expected_service:info
  unless on (namespace, workload)
label_replace(max by (namespace, deployment) (kube_deployment_spec_replicas), "workload", "$1", "deployment", "(.*)")
  unless on (namespace, workload)
label_replace(max by (namespace, name) (rollout_info_replicas_desired), "workload", "$1", "name", "(.*)")
  unless on (namespace, workload)
label_replace(max by (namespace, statefulset) (kube_statefulset_replicas), "workload", "$1", "statefulset", "(.*)")
"""

R5XX = f'label_replace(rate(http_server_requests_seconds_count{{status=~"5.."}}[10m]), {POD_TO_WORKLOAD})'
RALL = f'label_replace(rate(http_server_requests_seconds_count[10m]), {POD_TO_WORKLOAD})'
I5XX = f'label_replace(increase(http_server_requests_seconds_count{{status=~"5.."}}[10m]), {POD_TO_WORKLOAD})'
RESTARTS = f'label_replace(increase(kube_pod_container_status_restarts_total[30m]), {POD_TO_WORKLOAD})'

ERR_EXPR = f"""\
(
  sum by (namespace, workload) ({R5XX})
    / clamp_min(sum by (namespace, workload) ({RALL}), 0.001) > 0.05
)
and
(
  sum by (namespace, workload) ({I5XX}) >= 20
)
and on (namespace, workload) openbank:expected_service:info
"""

RESTART_EXPR = f"""\
sum by (namespace, workload) ({RESTARTS}) >= 3
and on (namespace, workload) openbank:expected_service:info
"""


def inventory(gitops: Path) -> list[tuple[str, str]]:
    return sorted((ns, w) for ns, ws in management_port_workloads(gitops).items() for w in ws)


def build(inv: list[tuple[str, str]]) -> dict:
    records = [
        {
            "record": "openbank:expected_service:info",
            "expr": "vector(1)",
            "labels": {"namespace": ns, "workload": w},
        }
        for ns, w in inv
    ]
    alerts = [
        {
            "alert": "ExpectedWorkloadAbsent",
            "expr": ABSENT_EXPR,
            "for": "30m",
            "labels": {"severity": "warning"},
            "annotations": {
                "summary": "Expected workload {{ $labels.workload }} ({{ $labels.namespace }}) does not exist",
                "description": (
                    "The deployed-service inventory lists {{ $labels.workload }} in {{ $labels.namespace }}, "
                    "but no Deployment, Rollout or StatefulSet series exists for it. It was deleted, never "
                    "synced, or renamed. Scale-to-zero does NOT trigger this (the object keeps its series). "
                    "Check the Argo CD Application for the component."
                ),
            },
        },
        {
            "alert": "ServiceHttp5xxRatioHigh",
            "expr": ERR_EXPR,
            "for": "10m",
            "labels": {"severity": "warning"},
            "annotations": {
                "summary": "{{ $labels.workload }} ({{ $labels.namespace }}) is answering >5% 5xx",
                "description": (
                    "More than 5% of HTTP responses from {{ $labels.workload }} were 5xx over 10m, with at "
                    "least 20 of them. Floor is absolute so a quiet service cannot trip it on two errors."
                ),
                "subject_period": "continuous",
            },
        },
        {
            "alert": "ServiceRestartBurst",
            "expr": RESTART_EXPR,
            "for": "5m",
            "labels": {"severity": "warning"},
            "annotations": {
                "summary": "{{ $labels.workload }} ({{ $labels.namespace }}) restarted 3+ times in 30m",
                "description": (
                    "Container restarts summed across the pods of {{ $labels.workload }} reached 3 in 30m: "
                    "crash loop, OOMKill or failing liveness probe. kubectl -n {{ $labels.namespace }} "
                    "describe pods | grep -A5 'Last State'."
                ),
                "subject_period": "continuous",
            },
        },
    ]
    return {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": "openbank-service-inventory-alerts",
            "namespace": "observability",
            "labels": {"app.kubernetes.io/part-of": "observability"},
        },
        "spec": {
            "groups": [
                {"name": "openbank.service.inventory", "interval": "1m", "rules": records},
                {"name": "openbank.service.baseline", "rules": alerts},
            ]
        },
    }


class _Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _str(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str)


def render(inv) -> str:
    return HEADER + "---\n" + yaml.dump(build(inv), Dumper=_Dumper, sort_keys=False, width=1000)


def self_test() -> int:
    inv = [("ledger", "ledger-service"), ("payments", "sepa-payment")]
    text = render(inv)
    doc = yaml.safe_load(text.split("---\n", 1)[1])
    recs = doc["spec"]["groups"][0]["rules"]
    assert len(recs) == 2 and recs[0]["labels"]["workload"] == "ledger-service", "one recording rule per workload"
    assert [r["alert"] for r in doc["spec"]["groups"][1]["rules"]] == [
        "ExpectedWorkloadAbsent", "ServiceHttp5xxRatioHigh", "ServiceRestartBurst"]
    assert render(inv) == text, "output must be deterministic"
    assert render(inv + [("x", "new-service")]) != text, "a new service must change the output"
    real = inventory(REPO / "openbank-infra/gitops")
    assert len(real) >= 30, f"inventory lost its corpus: {len(real)}"
    print("self-test OK")
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    inv = inventory(REPO / "openbank-infra/gitops")
    (REPO / OUT_REL).write_text(render(inv))
    print(f"gen-service-alert-rules: {len(inv)} workloads -> {OUT_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
