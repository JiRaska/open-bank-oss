'use client'

import { useState } from 'react'
import { Sparkles } from 'lucide-react'
import { useLanguage } from '@/lib/i18n/LanguageContext'

/** On-demand, tool-free AI explanation of one catalogue entry. The server builds the facts. */
export function KeyCustodianExplain({ entryId }: { entryId: string }) {
  const { language, t } = useLanguage()
  const [state, setState] = useState<'idle' | 'loading' | 'done' | 'unavailable'>('idle')
  const [text, setText] = useState('')
  const [model, setModel] = useState('')

  async function ask() {
    setState('loading')
    try {
      const res = await fetch('/api/security/keys/explain', {
        method: 'POST', headers: { 'Content-Type': 'application/json' }, cache: 'no-store',
        body: JSON.stringify({ entryId, language }),
      })
      if (!res.ok) throw new Error(String(res.status))
      const body = await res.json() as { explanation: string; model: string }
      setText(body.explanation); setModel(body.model); setState('done')
    } catch {
      setState('unavailable')
    }
  }

  if (state === 'idle' || state === 'loading') {
    return (
      <button type="button" className="btn btn-secondary btn-sm" onClick={() => void ask()} disabled={state === 'loading'} aria-busy={state === 'loading'}
        style={{ alignSelf: 'flex-start' }}>
        <Sparkles size={13} aria-hidden="true" /> {state === 'loading' ? t('Správce klíčů přemýšlí…', 'Key custodian is thinking…') : t('Vysvětlit (AI)', 'Explain (AI)')}
      </button>
    )
  }
  if (state === 'unavailable') {
    return <p role="status" style={{ margin: 0, fontSize: 12, color: 'var(--text-tertiary)' }}>{t('AI vysvětlení teď není k dispozici. Údaje na kartě platí dál.', 'AI explanation is unavailable right now. The facts on this card still stand.')}</p>
  }
  return (
    <div role="region" aria-label={t('Vysvětlení správce klíčů', 'Key custodian explanation')}
      style={{ border: '1px solid var(--ob-accent-border)', background: 'var(--ob-accent-light)', borderRadius: 10, padding: '10px 12px', fontSize: 13 }}>
      <div style={{ whiteSpace: 'pre-wrap' }}>{text}</div>
      <div style={{ marginTop: 6, fontSize: 11, color: 'var(--text-tertiary)' }}>
        {t('Vygenerováno AI bez přístupu k nástrojům a bez jakéhokoli klíče', 'Generated by AI with no tool access and no key material')} · {model}
      </div>
    </div>
  )
}
