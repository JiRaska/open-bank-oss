// Generate the browser-safe domain contract from the shared governance taxonomy.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import taxonomySource from '../../openbank-libs/governance/domain-taxonomy.json' with { type: 'json' }

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/lib/governance/domains.ts')
export const taxonomy = taxonomySource
if (taxonomy.schema !== 'openbank.domain-taxonomy/v1' || !Array.isArray(taxonomy.domains)
  || taxonomy.domains.length === 0 || new Set(taxonomy.domains.map(d => d.id)).size !== taxonomy.domains.length) {
  throw new Error('Invalid or duplicate domain taxonomy')
}
for (const d of taxonomy.domains) {
  if (!/^[a-z][a-z-]*$/.test(d.id) || !['business', 'supporting', 'platform'].includes(d.kind)
    || ['labelEn', 'labelCs', 'description', 'color'].some(k => typeof d[k] !== 'string' || !d[k].trim())) {
    throw new Error(`Invalid domain definition: ${d.id}`)
  }
}
export const domainIds = taxonomy.domains.map(d => d.id)
const metadata = Object.fromEntries(taxonomy.domains.map(({ id, ...meta }) => [id, meta]))
export const generatedSource = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/generate-domain-taxonomy.mjs. Edit openbank-libs/governance/domain-taxonomy.json.
export const DOMAIN_IDS = ${JSON.stringify(domainIds)} as const
export type DomainId = typeof DOMAIN_IDS[number]
export type DomainGroup = DomainId | 'unclassified'
export const DOMAIN_GROUPS = [...DOMAIN_IDS, 'unclassified'] as const
export const DOMAIN_META = ${JSON.stringify(metadata, null, 2)} as const
export function isDomainId(value: unknown): value is DomainId {
  return typeof value === 'string' && (DOMAIN_IDS as readonly string[]).includes(value)
}
export function domainLabel(value: string, language: 'cs' | 'en'): string {
  if (!isDomainId(value)) return language === 'cs' ? 'Nezařazeno' : 'Unclassified'
  return language === 'cs' ? DOMAIN_META[value].labelCs : DOMAIN_META[value].labelEn
}
export function domainColor(value: string): string {
  return isDomainId(value) ? DOMAIN_META[value].color : 'var(--text-tertiary)'
}
`
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== generatedSource) throw new Error('Domain contract drift: run node scripts/generate-domain-taxonomy.mjs')
  } else writeFileSync(target, generatedSource)
}
