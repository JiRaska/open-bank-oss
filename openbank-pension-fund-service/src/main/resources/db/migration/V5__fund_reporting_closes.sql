-- Immutable aggregate reporting evidence for an explicit fund close (ADR-0339, #12425).
-- A changed source fingerprint after a NAV or classification correction is a new row.
-- Rollback: disable close creation/read first. Preserve both tables if a receipt exists or any
-- statutory return cites a close id. Only on an unused deployment may the receipt trigger/table,
-- close trigger/table and function be dropped in that order; the live GET remains available.
CREATE TABLE fund_reporting_closes (
    id UUID PRIMARY KEY,
    revision BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    fund_id UUID NOT NULL REFERENCES funds(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    closing_nav_id UUID NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    payload_schema_version VARCHAR(32) NOT NULL,
    payload_json TEXT NOT NULL,
    payload_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_fund_reporting_close_source
      UNIQUE (fund_id, period_start, period_end, source_fingerprint, payload_schema_version),
    CONSTRAINT ck_fund_reporting_close_period CHECK (period_start <= period_end)
);
CREATE INDEX ix_fund_reporting_closes_scope
  ON fund_reporting_closes (fund_id, period_end, revision);

-- A successful command receipt survives source corrections. A request key is scoped to the
-- authenticated actor and fund; repeated requests return its original close without recomputing.
CREATE TABLE fund_reporting_close_receipts (
    fund_id UUID NOT NULL REFERENCES funds(id),
    actor VARCHAR(255) NOT NULL,
    idempotency_key CHAR(64) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    close_id UUID NOT NULL REFERENCES fund_reporting_closes(id),
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (actor, idempotency_key)
);

-- Same pattern as ledger's frozen trial-balance evidence: a future repository change must not
-- rewrite an acknowledged source close, even if it accidentally issues UPDATE or DELETE.
CREATE FUNCTION reject_fund_reporting_close_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'fund_reporting_closes is immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_fund_reporting_close_immutable
    BEFORE UPDATE OR DELETE ON fund_reporting_closes
    FOR EACH ROW EXECUTE FUNCTION reject_fund_reporting_close_mutation();

CREATE TRIGGER trg_fund_reporting_close_receipt_immutable
    BEFORE UPDATE OR DELETE ON fund_reporting_close_receipts
    FOR EACH ROW EXECUTE FUNCTION reject_fund_reporting_close_mutation();
